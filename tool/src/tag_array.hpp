// The run-length compressed tag array (Section 4 of the paper, "Counting with complete tag arrays").  The
// tag array gives, for each BWT row, the tag (taxon) of the suffix starting there.  We store it by its
// rho tag runs:
//   RB    Elias-Fano list of the first row of every run;
//   L     the tag of every run, or of the sampled runs only (s > 1), or none (grammar-compressed: G).
// Counting (proportional credit): scan the runs that overlap [sp, ep), adding up their clipped lengths.
// Listing (even credit; the smallest and largest tags, for the range scheme and LCAs): the distinct tags
// in [sp, ep) by Muthukrishnan's method without the previous-run array (Sadakane's trick): an RMQ over
// C[i] = 1 + the previous run with the same tag as run i (0 if none), which does not store C (rmq.hpp),
// plus marks for the tags already reported.
// Sampling (s > 1): LF from a run's first row stays in the same genome except at a genome's first
// character, so a run's tag is that of the run containing LF of its first row; only some runs' tags are
// stored (SB marks them), so that every run reaches a sampled one in fewer than s LF steps, one per cycle.
// Grammar (G): the sequence of the runs' tags generated by a RePair grammar (grammar.hpp).
#pragma once
#include "grammar.hpp"
#include "rlcsa.hpp"
#include "rmq.hpp"

namespace katka {

struct tag_array {
    u64 n = 0, rho = 0, s = 1;
    EliasFano RB;
    BitRank SB;
    PackedInts L;
    std::unique_ptr<tag_grammar> G;
    succinct_rmq rmq; bool has_rmq = false;
    const rlbwt *bwt = nullptr;                     // for LF, when s > 1
    const rlcsa *csa = nullptr;                     // for LF instead of bwt, if set (no RLBWT is needed then)
    uint64_t (*lf_hook)(uint64_t) = nullptr;        // LF from elsewhere, if set (the Movi 2 prototype)

    static inline thread_local std::vector<uint32_t> cnt;
    static inline thread_local std::vector<char> mark;
    static inline thread_local std::vector<u64> touched;
    static inline thread_local u64 lf_steps = 0;

    u64 run_of(u64 row) const { return RB.count_less(row + 1) - 1; }
    u64 run_start(u64 i) const { return RB.access(i); }

    u64 tag(u64 i) const {
        if (G) { u64 t = 0; G->decode(i, 1, [&](uint32_t g) { t = g; }); return t; }
        if (s == 1) return L[i];
        while (!SB.get(i)) {
            u64 b = run_start(i);
            i = run_of(lf_hook ? lf_hook(b) : csa ? csa->LF(b) : bwt->LF(b)); ++lf_steps;
        }
        return L[SB.rank1(i)];
    }
    // calls f(run, tag) for runs a..b
    template <class F> void tags_of(u64 a, u64 b, F f) const {
        if (G) { u64 i = a; G->decode(a, b - a + 1, [&](uint32_t g) { f(i++, (u64)g); }); return; }
        for (u64 i = a; i <= b; ++i) f(i, tag(i));
    }

    // (tag, number of rows of [sp, ep) with that tag), sorted by tag
    void count(u64 sp, u64 ep, std::vector<std::pair<u64, u64>> &out) const {
        out.clear();
        u64 a = run_of(sp), b = run_of(ep - 1);
        if (a == b) { out.push_back({tag(a), ep - sp}); return; }
        if (cnt.empty()) cnt.assign(1 << 16, 0);
        u64 st = sp;
        tags_of(a, b, [&](u64 i, u64 t) {
            u64 en = i < b ? run_start(i + 1) : ep;
            if (t >= cnt.size()) cnt.resize(t + 1, 0);
            if (cnt[t] == 0) touched.push_back(t);
            cnt[t] += (uint32_t)(en - st);
            st = en;
        });
        for (u64 t : touched) { out.push_back({t, cnt[t]}); cnt[t] = 0; }
        touched.clear();
        std::sort(out.begin(), out.end());
    }

    // the distinct tags of rows [sp, ep), appended to out (unsorted)
    void list(u64 sp, u64 ep, std::vector<u64> &out) const {
        if (!has_rmq) die("listing needs the RMQ (build the tags without --no-rmq)");
        if (mark.empty()) mark.assign(1 << 16, 0);
        u64 a = run_of(sp), b = run_of(ep - 1);
        report(tag(a), out);
        if (b > a) list_rec(a + 1, b, out);
        for (u64 t : touched) mark[t] = 0;
        touched.clear();
    }

    u64 bytes() const {
        return RB.bytes() + L.bytes() + (s > 1 ? SB.bytes() : 0) + (G ? G->bytes() : 0) + (has_rmq ? rmq.bytes() : 0);
    }
    void save(const std::string &f) const {
        FILE *o = open_or_die(f, "wb");
        wmagic(o, "KTTAG001"); wr(o, n); wr(o, rho); wr(o, s);
        uint8_t g = G ? 1 : 0; wr(o, g);
        RB.save(o);
        if (s > 1) SB.save(o);
        if (G) G->save(o); else L.save(o);
        fclose(o);
        if (has_rmq) { FILE *r = open_or_die(f + ".rmq", "wb"); wmagic(r, "KTRMQ001"); rmq.save(r); fclose(r); }
    }
    void load(const std::string &f, bool with_rmq) {
        FILE *i = open_or_die(f, "rb");
        rmagic(i, "KTTAG001", f);
        uint8_t g = 0;
        rd(i, n); rd(i, rho); rd(i, s); rd(i, g);
        RB.load(i);
        if (s > 1) SB.load(i);
        if (g) { G.reset(new tag_grammar); G->load(i); } else L.load(i);
        fclose(i);
        if (!with_rmq) return;
        if (!file_exists(f + ".rmq")) die(f + ".rmq missing: listing needs the RMQ (build the tags without --no-rmq)");
        FILE *r = open_or_die(f + ".rmq", "rb");
        rmagic(r, "KTRMQ001", f + ".rmq");
        rmq.load(r); fclose(r);
        has_rmq = true;
    }

private:
    void report(u64 t, std::vector<u64> &out) const {
        if (t >= mark.size()) mark.resize(t + 1, 0);
        mark[t] = 1; touched.push_back(t); out.push_back(t);
    }
    // runs [l, r]: a run k with the smallest C[k] has a tag that is new iff it is not marked; if it is
    // marked, every tag in [l, r] already occurs earlier, so stop (left part before right part)
    void list_rec(u64 l, u64 r, std::vector<u64> &out) const {
        u64 k = rmq(l, r), t = tag(k);
        if (t < mark.size() && mark[t]) return;
        report(t, out);
        if (k > l) list_rec(l, k - 1, out);
        if (k < r) list_rec(k + 1, r, out);
    }
};

}  // namespace katka
